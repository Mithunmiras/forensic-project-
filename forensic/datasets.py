"""Dataset profiles: what each dataset contains and how the agents should read it.

The agents are generic over product / region / month. A profile tells them which signals exist
(inventory stock-outs vs. late deliveries, discounts, prices), how to label them, how to build
the baseline, and which thresholds make a change material.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from forensic import config as C


@dataclass(frozen=True)
class Dataset:
    key: str
    title: str
    description: str
    root: Path
    regions: tuple
    region_patterns: tuple            # (regex, region) pairs, tried in order
    has_inventory: bool               # supply signal = stock-out days (else late-delivery rate)
    has_discount: bool
    has_price: bool
    has_ground_truth: bool
    currency: str
    returns_label: str
    baseline_window: Optional[int]    # months either side for the baseline; None = all other months
    doc_lookback_days: int
    thresholds: dict = field(default_factory=dict)
    floors: dict = field(default_factory=dict)
    source: str = ""

    @property
    def structured_dir(self) -> Path:
        return self.root / "structured"

    @property
    def unstructured_dir(self) -> Path:
        return self.root / "unstructured"

    @property
    def catalog_path(self) -> Path:
        return self.structured_dir / "catalog.json"

    def is_available(self) -> bool:
        return (self.structured_dir / "sales.csv").exists() and self.catalog_path.exists()

    def public(self) -> dict:
        return {"key": self.key, "title": self.title, "description": self.description, "regions": list(self.regions),
                "has_inventory": self.has_inventory, "has_discount": self.has_discount, "has_price": self.has_price,
                "has_ground_truth": self.has_ground_truth, "currency": self.currency,
                "returns_label": self.returns_label, "baseline_window": self.baseline_window, "source": self.source,
                "units_pct_threshold": self.thresholds.get("units_pct"),
                "available": self.is_available()}


SYNTHETIC = Dataset(
    key="synthetic", title="Synthetic (ground truth)",
    description="Apple-style catalogue with 18 injected incidents and 6 controls; every cause is known, so accuracy "
                "can be scored.",
    root=C.DATA_DIR, regions=("North", "South", "East", "West"),
    region_patterns=((r"\bnorth(ern)?\b", "North"), (r"\bsouth(ern)?\b", "South"),
                     (r"\beast(ern)?\b", "East"), (r"\bwest(ern)?\b", "West")),
    has_inventory=True, has_discount=True, has_price=True, has_ground_truth=True, currency="$",
    returns_label="returns rate", baseline_window=None, doc_lookback_days=C.DOC_LOOKBACK_DAYS,
    thresholds={"z": C.Z_THRESHOLD, "units_pct": C.UNITS_PCT_THRESHOLD, "returns_pct": C.RETURNS_PCT_THRESHOLD,
                "discount_pp": C.DISCOUNT_PP_THRESHOLD, "price_pct": C.PRICE_PCT_THRESHOLD,
                "stockout_days": C.STOCKOUT_DAYS_THRESHOLD},
    # metric -> (minimum scale as a fraction of the baseline, absolute minimum scale)
    floors={"units_per_day": (0.015, 0.0), "returns_rate": (0.08, 0.0), "avg_discount": (0.0, 0.3),
            "price_index": (0.005, 0.0)},
    source="Generated by forensic/generate.py from forensic/scenarios.py",
)

OLIST = Dataset(
    key="olist", title="Real: Olist Brazil e-commerce",
    description="Real orders (2017-03 to 2018-08) and real customer reviews from the Olist marketplace; "
                "8 largest product categories across Brazil's 5 macro-regions. No answer key exists.",
    root=C.DATA_DIR / "olist", regions=("North", "Northeast", "Center-West", "Southeast", "South"),
    region_patterns=((r"\b(north[- ]?east(ern)?|nordeste)\b", "Northeast"),
                     (r"\b(south[- ]?east(ern)?|sudeste)\b", "Southeast"),
                     (r"\b(cent(er|re|ral)[- ]?west(ern)?|centro[- ]?oeste|mid[- ]?west)\b", "Center-West"),
                     (r"\b(north(ern)?|norte)\b", "North"), (r"\b(south(ern)?|sul)\b", "South")),
    has_inventory=False, has_discount=False, has_price=False, has_ground_truth=False, currency="R$",
    returns_label="share of 1–2★ reviews", baseline_window=3, doc_lookback_days=0,
    # Real marketplace data is far noisier than the synthetic set, so "material" is set higher.
    # min_units / min_delivered: a month needs this much volume before any rate can be called unusual.
    thresholds={"z": 3.0, "units_pct": 25.0, "returns_pct": 60.0, "late_pct": 100.0, "late_min": 8.0,
                "min_units": 60, "min_delivered": 40},
    floors={"units_per_day": (0.10, 0.5), "returns_rate": (0.20, 3.0), "late_rate": (0.25, 3.0)},
    source="Olist Brazilian E-Commerce Public Dataset (Kaggle: olistbr/brazilian-ecommerce), CC BY-NC-SA 4.0",
)

DATASETS = {d.key: d for d in (SYNTHETIC, OLIST)}
DEFAULT = "synthetic"


def get_dataset(key: Optional[str]) -> Dataset:
    ds = DATASETS.get(key or DEFAULT)
    if ds is None:
        raise KeyError(f"Unknown dataset {key!r}; choose one of {', '.join(DATASETS)}")
    return ds
